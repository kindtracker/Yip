const Parser = require("@babel/parser");
const Traverse = require("@babel/traverse").default;
const Generate = require("@babel/generator").default;
const Types = require("@babel/types");

const Globals = new Set([]);

function RewriteWindowApi(Path, Name) {
  const Parent = Path.parentPath;

  const IsDirectReference =
    Path.isReferencedIdentifier({ name: Name }) && !Path.scope.hasBinding(Name);

  const IsWindowReference =
    Parent?.isMemberExpression() &&
    Parent.get("object").isIdentifier({ name: "window" }) &&
    ((!Parent.node.computed &&
      Parent.get("property").isIdentifier({ name: Name })) ||
      (Parent.node.computed &&
        Parent.get("property").isStringLiteral({ value: Name })));

  if (!IsDirectReference && !IsWindowReference) {
    return;
  }

  const Member = Types.memberExpression(
    Types.memberExpression(
      Types.identifier("window"),
      Types.identifier("_yipenv"),
    ),
    Types.identifier(Name),
  );

  if (IsWindowReference) {
    Parent.replaceWith(Member);
  } else {
    Path.replaceWith(Member);
  }
}

function RewriteJavaScript(Source) {
  const Ast = Parser.parse(Source, {
    sourceType: "unambiguous",
    plugins: ["dynamicImport", "importMeta"],
  });

  Traverse(Ast, {
    ReferencedIdentifier(Path) {
      if (
        Path.findParent(
          (Parent) =>
            Parent.isMemberExpression() &&
            Parent.get("object").isIdentifier({ name: "window" }) &&
            Parent.get("property").isIdentifier({ name: "_yipenv" }),
        )
      ) {
        return;
      }

      const Name = Path.node.name;

      if (Globals.has(Name)) {
        RewriteWindowApi(Path, Name);
      }
    },
  });

  return Generate(Ast).code;
}

